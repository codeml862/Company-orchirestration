"""Object storage for client uploads, agent work products and deliverables.

The local-disk backend is used in development and single-host Docker deployments; the
interface is deliberately small so an S3/MinIO backend can replace it without touching callers.
Keys are generated by the platform (never by users or agents), which rules out path traversal.
"""

import hashlib
import uuid
from pathlib import Path

from sqlalchemy.orm import Session

from app.config import get_settings
from app.models import Artifact


class LocalStorage:
    def __init__(self, root: str):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise ValueError("invalid storage key")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_bytes(data)
        tmp.replace(path)

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


_storage: LocalStorage | None = None


def get_storage() -> LocalStorage:
    global _storage
    if _storage is None:
        _storage = LocalStorage(get_settings().storage_dir)
    return _storage


def reset_storage() -> None:
    global _storage
    _storage = None


TEXT_TYPES = ("text/", "application/json", "application/xml", "application/x-yaml", "application/csv")


def is_text(content_type: str) -> bool:
    return content_type.startswith(TEXT_TYPES)


def save_artifact(
    db: Session,
    *,
    project_id: uuid.UUID,
    kind: str,
    name: str,
    data: bytes,
    content_type: str = "text/plain",
    task_id: uuid.UUID | None = None,
    agent_id: uuid.UUID | None = None,
) -> Artifact:
    artifact_id = uuid.uuid4()
    key = f"projects/{project_id}/{kind}/{artifact_id}"
    get_storage().put(key, data)
    artifact = Artifact(
        id=artifact_id,
        project_id=project_id,
        task_id=task_id,
        agent_id=agent_id,
        kind=kind,
        name=Path(name).name[:300] or "file",
        content_type=content_type,
        storage_key=key,
        size_bytes=len(data),
        sha256=hashlib.sha256(data).hexdigest(),
    )
    db.add(artifact)
    db.flush()
    return artifact


def read_artifact(artifact: Artifact) -> bytes:
    return get_storage().get(artifact.storage_key)
